import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = path.resolve(import.meta.dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const search = JSON.parse(read('app/cards/search-metadata.json'));
const media = JSON.parse(read('app/cards/media.json'));
const origin = read('app/site-config.js').match(/SITE_ORIGIN = '([^']+)'/)[1];
const decode = value => value.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#x27;|&#39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>');
const tags = (html, tag) => [...html.matchAll(new RegExp(`<${tag}\\b[^>]*>`, 'g'))].map(match => Object.fromEntries([...match[0].matchAll(/([\w:-]+)="([^"]*)"/g)].map(m => [m[1], decode(m[2])])));
const meta = (html, name) => tags(html, 'meta').find(tag => tag.name === name || tag.property === name)?.content;
const canonical = html => tags(html, 'link').find(tag => tag.rel === 'canonical')?.href;
const schema = html => [...html.matchAll(/<script type="application\/ld\+json">(.*?)<\/script>/gs)].map(m => JSON.parse(m[1]));
assert.equal(Object.keys(search).length, 50);
assert.deepEqual(Object.keys(search).sort(), Object.keys(media).sort());
const titles = new Set(), descriptions = new Set(), images = new Set();
let clues = 0, books = 0;
for (const [slug, data] of Object.entries(search)) {
  const html = read(`.next/server/app/cards/${slug}.html`);
  const url = `${origin}/cards/${slug}`;
  const title = decode(html.match(/<title>(.*?)<\/title>/s)[1]);
  assert.equal(title, `${data.title} | HISTROVE`);
  assert.equal(meta(html, 'description'), data.description);
  assert.equal(meta(html, 'twitter:title'), title);
  assert.equal(meta(html, 'twitter:description'), data.description);
  assert.equal(meta(html, 'og:title'), title);
  assert.equal(meta(html, 'og:description'), data.description);
  assert.equal(meta(html, 'og:url'), url);
  assert.equal(canonical(html), url);
  const actions = html.match(/<div class="story-art-actions">.*?<\/div>/s)?.[0];
  assert(actions && actions.includes('href="/shop#booster-packs"'), slug + ': paired booster preview link');
  assert(actions.indexOf('Explore booster packs') < actions.indexOf('Explore the full art'));
  assert.equal(tags(actions, 'a').length, 1);
  assert(!html.includes('story-shop-note'), slug + ': no duplicate below-story CTA');
  assert(!html.includes('↗'), slug + ': no system/emoji link arrows');
  assert(html.includes('class="link-icon"'), slug + ': outline SVG link icons');
  assert.equal(meta(html, 'og:type'), 'article');
  assert.equal(meta(html, 'twitter:image'), origin + media[slug].artwork.src);
  assert.equal(meta(html, 'og:image'), origin + media[slug].artwork.src);
  titles.add(title); descriptions.add(data.description); images.add(meta(html, 'og:image'));
  const schemas = schema(html);
  assert.equal(schemas.find(s => s['@type'] === 'WebSite').name, 'HISTROVE');
  const graph = schemas.find(s => s['@graph'])['@graph'];
  const article = graph.find(s => s['@type'] === 'Article');
  assert.equal(article.mainEntityOfPage, url);
  assert(!article.datePublished && !article.dateModified && !article.author && !article.offers);
  assert.equal(graph.find(s => s['@type'] === 'BreadcrumbList').itemListElement[1].item, url);
  const number = media[slug].image.src.match(/\/(\d{3})-/)[1];
  const chapter = JSON.parse(read(`app/cards/content/${number}.json`));
  const cluePanel = html.match(/<section role="tabpanel" id="panel-clues".*?<\/section>/s)?.[0];
  const bookPanel = html.match(/<section role="tabpanel" id="panel-book".*?<\/section>/s)?.[0];
  assert(cluePanel && bookPanel, slug + ': server-rendered supplemental panels');
  for (const egg of chapter.eggs) {
    assert(decode(cluePanel).includes(egg.title), `${slug}: clue title in HTML`);
    assert(decode(cluePanel).includes(egg.text.split(/\*|\[/)[0]), `${slug}: clue text in HTML`);
    clues++;
  }
  assert(decode(bookPanel).includes(media[slug].originalBook), slug + ': book PDF link in HTML');
  assert.equal(tags(bookPanel, 'img').length, 2);
  for (const img of tags(bookPanel, 'img')) assert.equal(img.loading, 'lazy');
  for (const img of tags(cluePanel, 'img')) assert.equal(img.loading, 'lazy');
  books += 2;
}
assert.equal(titles.size, 50); assert.equal(descriptions.size, 50); assert.equal(images.size, 50);
assert.equal(clues, 212); assert.equal(books, 100);
const home = read('.next/server/app/index.html');
assert.equal(new URL(canonical(home)).href, origin + '/');
assert(home.includes('Email registration opens soon'));
const launch = home.match(/<section class="coming-soon".*?<\/section>/s)[0];
assert(launch.includes('does not collect or store email addresses'));
assert.equal(tags(launch, 'input').length, 2);
assert.equal((launch.match(/<input[^>]* disabled=""/g) || []).length, 2);
assert(/<button[^>]*type="button"[^>]*disabled=""/.test(launch));
assert(!launch.includes('<form') && !launch.includes('action='));
const shop = read('.next/server/app/shop.html');
assert.equal(canonical(shop), origin + '/shop');
assert(shop.includes('Purchases aren’t open yet'));
assert(shop.includes('id="booster-packs"'));
assert(shop.includes('10-card booster pack') && shop.includes('Crypto history companion book'));
assert(shop.includes('Booster packs — coming soon') && shop.includes('Book — coming soon'));
assert(shop.includes('id="launch-details"'));
assert(!shop.includes('ART DISPLAY') && !shop.includes('proposed display frame'));
assert.equal((shop.match(/class="retail-cta"/g)||[]).length, 2);
assert(!shop.includes('<form') && !shop.includes('Add to cart') && !shop.includes('Buy now'));
assert(home.includes('Explore the shop') && home.includes('Explore the timeline'));
const sitemap = read('.next/server/app/sitemap.xml.body');
const urls = [...sitemap.matchAll(/<loc>(.*?)<\/loc>/g)].map(m => decode(m[1]));
assert.equal(urls.length, 52); assert.equal(new Set(urls).size, 52); assert(urls.includes(origin + '/shop'));
assert(urls.includes(origin + '/'));for (const slug of Object.keys(search)) assert(urls.includes(origin + '/cards/' + slug));
assert(!sitemap.includes('<lastmod>') && !sitemap.includes('/crypto/'));
const robots = read('.next/server/app/robots.txt.body');
assert(robots.includes('Allow: /') && robots.includes(`Sitemap: ${origin}/sitemap.xml`));
const helper = read('app/seo.js').match(/export function jsonLd\(value\) \{(.*?)\}/s)[1];
const safeJson = new Function('value', helper)({ text: '</script><script>alert(1)</script>' });
assert(!safeJson.includes('<')); assert.equal(JSON.parse(safeJson).text, '</script><script>alert(1)</script>');
console.log(`PASS: 52 canonical pages, 50 unique descriptive titles/descriptions/social images, 212 SSR clues, 100 lazy book previews, sitemap/robots, truthful closed signup and safe JSON-LD`);
