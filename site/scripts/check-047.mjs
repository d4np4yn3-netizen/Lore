import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const h=p=>createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const read=p=>JSON.parse(fs.readFileSync(p));
const m=read('media/047-manifest.json'),data=read('app/cards/content/047.json'),media=read('app/cards/media.json')['dai-goes-live'];
for(const r of [m.art,m.book,m.chapter,...Object.values(m.print)])assert.equal(h('../'+r.path),r.sha256);
for(const a of m.assets)assert.equal(h('public/'+a.path),a.sha256);
assert.equal(m.art.sha256,'e144c21d3a83cf3f96b39ffb1822f7bc4848fafd96769dc15610cc3c95e93bd8');
assert.equal(data.story.length,5);assert.equal(data.eggs.length,4);assert.equal(media.pages.length,2);
assert.equal(media.originalBook,m.book.path);assert.equal(media.originalArt,m.art.path);
assert.equal(m.qr,'https://lore-site-v1.vercel.app/crypto/047/');
assert(fs.readFileSync('app/crypto/047/page.js','utf8').includes('/cards/dai-goes-live'));
const chapter=fs.readFileSync('../'+m.chapter.path,'utf8');
for(const p of data.story)assert(chapter.includes(p));
for(const e of data.eggs){assert(chapter.includes(e.title));assert(chapter.includes(e.text));}
assert(chapter.includes(data.sourceNote));
assert(data.story[0].includes('18 December 2017'));assert(data.story[2].includes('soft peg'));
assert(data.eggs[3].text.includes('full illustration'));assert(!JSON.stringify(data).includes('single gold fill'));
const prior=read('media/pre047-preservation.json'),allMedia=read('app/cards/media.json'),allCloseups=read('app/cards/closeups.json'),allIndex=read('media/index.json');
for(const [slug,record] of Object.entries(prior.media))assert.deepEqual(allMedia[slug],record);
for(const [id,record] of Object.entries(prior.closeups))assert.deepEqual(allCloseups[id],record);
for(const record of prior.index.assets)assert.deepEqual(allIndex.assets.find(a=>a.path===record.path),record);
assert.equal(allIndex.assets.length,prior.index.assets.length+8);
const registry=read('../cards/crypto/current-cards.json'),r=registry.cards.find(c=>c.id==='crypto-s01-dai-goes-live');
for(const old of prior.registry.cards)assert.deepEqual(registry.cards.find(c=>c.id===old.id),old);
assert.equal(registry.cards.length,prior.registry.cards.length+1);assert.equal(r.moment_number,47);assert.equal(r.title_line_1,'DAI');assert.equal(r.title_line_2,'GOES LIVE');assert.equal(r.rarity,'rare');assert.equal(r.creator,'MAKERDAO');assert.equal(r.context,'DAI IS NOW LIVE!');assert.equal(r.qr_mode,'live');assert.equal(r.qr_url,m.qr);assert.equal(registry.cards.filter(c=>c.moment_number===47).length,1);
assert.equal(r.artwork_file.sha256,m.art.sha256);assert.equal(r.print_ready.pdf.sha256,m.print.pdf.sha256);assert.equal(r.print_release,false);
const master='../cards/crypto/season-01/dai-goes-live-master-047/';
const sealed=read(master+'immutable-package-manifest.json');for(const f of sealed.files)assert.equal(h(master+f.path),f.sha256);
assert.equal(read(master+'approval.json').artwork_revision,'gold-level-v8');
assert.equal(read(master+'card-final-qa.json').svg_embedded_art_exact,true);
console.log('PASS: 047 exact v8 art/print/book/chapter, sealed package hashes, eight display hashes, five shared paragraphs, four full-art clues, stable QR, soft-peg qualification; all 48 prior card objects and 536 display assets preserved');
